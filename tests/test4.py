import sys
from playwright.sync_api import sync_playwright
ok=True
def chk(n,c,i=''):
    global ok; print(('PASS ' if c else 'FAIL ')+n, i); ok = ok and bool(c)
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1440,'height':900}); errs=[]
    pg.on('console', lambda m: errs.append(m.text) if m.type=='error' and 'fonts' not in m.text and 'ERR_' not in m.text else None); pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.goto('file://'+sys.argv[1]); pg.wait_for_timeout(1200)
    pg.click('#tree .tnode[data-sel=task][data-id=t1]'); pg.wait_for_timeout(300)
    chk('thumb dùng dấu +', pg.locator('#tree .ed .ithumb span').first.inner_text()=='+')
    chk('không còn ✦', '✦' not in pg.evaluate("document.body.innerText"))
    r=pg.evaluate("""()=>{const b=document.querySelector('#tree .ed .imgrow2');if(!b)return null;const t=b.querySelector('.ithumb').getBoundingClientRect(),i=b.querySelector('input').getBoundingClientRect();return [t.right,i.left,t.top,i.top]}""")
    chk('v83: ô chữ nằm bên phải ô ảnh (hai cột)', r and r[1]>=r[0]-1 and abs(r[2]-r[3])<70, r)
    pg.click('#tree .tnode[data-sel=task][data-id=t16]'); pg.wait_for_timeout(300)
    nrows=pg.evaluate("ws.tasks.find(t=>t.id==='t16').content.rows.length")
    ids=pg.evaluate("ws.tasks.find(t=>t.id==='t16').content.rows.map(r=>r.id)")
    chk('hàng có id', all(ids) and len(set(ids))==nrows, ids)
    th=pg.locator('#tree .ed .etr .ithumb').count(); chk('ô ảnh trong bảng có thumb', th>0, th)
    if th:
        pg.locator('#tree .ed .etr .ithumb').first.click(); pg.wait_for_timeout(300)
        chk('popup mở cho ô bảng', pg.evaluate("document.getElementById('genDlg').open"), pg.inner_text('#genTitle'))
        chk('ô bảng: có panel khung', pg.evaluate("!document.getElementById('genFrame').hidden"))
        pg.evaluate("document.getElementById('genDlg').close()")
        k=pg.evaluate("slotsOf(ws.tasks.find(t=>t.id==='t16')).map(s=>s.key)"); chk('slotsOf có ô bảng', len(k)>0, k)
        pg.evaluate("""()=>{const t=ws.tasks.find(x=>x.id==='t16');const k=slotsOf(t)[0].key;commit(w=>{const tt=w.tasks.find(x=>x.id==='t16');tt.uploads=tt.uploads||{};tt.uploads[k]='data:image/gif;base64,R0lGODlhAQABAAAAACw=';})}""")
        pg.wait_for_timeout(400)
        chk('ảnh hiện trên phiếu', pg.evaluate("[...document.querySelectorAll('.task[data-task=t16] .pic img')].length")>0)
    # khung trong popup: G1 của Task có ảnh chung (câu hỏi, bài đọc, chỉ có ảnh)
    g=pg.evaluate("ws.tasks.filter(t=>t.image&&['questions','passage','empty'].includes(ck(t))).map(t=>t.id)"); print('task G1',g)
    chk('Task chỉ có ảnh (t10) có khung G1', 't10' in g, g)
    for tid in [g[0], 't10']:
        pg.click(f'#tree .tnode[data-sel=task][data-id={tid}]'); pg.wait_for_timeout(300)
        pg.evaluate(f"openGen('{tid}','G1')"); pg.wait_for_timeout(300)
        chk(tid+' G1: panel khung hiện', pg.evaluate("!document.getElementById('genFrame').hidden"))
        pg.set_input_files('#genRefFile','ref.png') ; pg.wait_for_timeout(200)
        pg.evaluate("document.getElementById('genGo').click()"); pg.wait_for_timeout(2500)
        chk(tid+' ô chưa có ảnh: mặc định Fit ngang', pg.evaluate("document.querySelector('#genFit .on').dataset.fit")=='width')
        pg.click('#genFit [data-fit=height]'); pg.wait_for_timeout(200)
        chk(tid+' chỉnh nháp: chưa ghi vào layout', pg.evaluate(f"ws.tasks.find(t=>t.id==='{tid}').layout.frame.fit")!='height')
        pg.fill('#genZoom','150'); pg.dispatch_event('#genZoom','change'); pg.wait_for_timeout(200)
        pg.click('#genUse'); pg.wait_for_timeout(700)
        chk(tid+' Dùng ảnh này: ghi Fit dọc', pg.evaluate(f"ws.tasks.find(t=>t.id==='{tid}').layout.frame.fit")=='height')
        chk(tid+' Dùng ảnh này: ghi zoom', pg.evaluate(f"ws.tasks.find(t=>t.id==='{tid}').layout.frame.zoom")==150)
        pg.evaluate(f"openGen('{tid}','G1')"); pg.wait_for_timeout(300)
        pg.click('#genFit [data-fit=width]'); pg.click('#genClose'); pg.wait_for_timeout(200)
        chk(tid+' x: không lưu Fit', pg.evaluate(f"ws.tasks.find(t=>t.id==='{tid}').layout.frame.fit")=='height')
        chk('không còn dòng demo / ghi chú / nút Đóng', pg.evaluate("!document.getElementById('genCancel') && !document.getElementById('genFrameNote') && document.getElementById('genNote').textContent===''"))
        pg.evaluate("document.getElementById('genDlg').close()")
    print('ERRS',errs); print('ALL OK' if ok and not errs else 'SOME FAIL')
