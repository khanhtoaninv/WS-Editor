# v80: ký hiệu chữ (đậm / nghiêng / gạch chân), tự tách phần, khung viết tự do, gạch ___ trong câu, xóa khung ảnh
# Dữ liệu thật: tests/real/dieu-chinh-v80.md (MD người dùng gửi, thêm Task 6 để thử ký hiệu)
import sys, os, re
from playwright.sync_api import sync_playwright
F = 'file://' + sys.argv[1]; ok = True
HERE = os.path.dirname(os.path.abspath(__file__))
MD = open(os.path.join(HERE, 'real', 'dieu-chinh-v80.md'), encoding='utf-8').read()
def chk(n, c, x=''):
    global ok; print(('PASS ' if c else 'FAIL '), n, x); ok &= bool(c)
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1440, 'height': 1000}); errs = []
    pg.on('pageerror', lambda e: errs.append('PAGEERR ' + str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'ERR_' not in m.text and 'font' not in m.text.lower() else None)
    pg.goto(F); pg.wait_for_timeout(1200)
    chk('badge ≥ v80', int(re.sub(r'\D', '', pg.evaluate("document.getElementById('verBadge').textContent")) or 0) >= 80)
    R = lambda s, pw=False: pg.evaluate("([s,pw])=>rich(esc(s),pw)", [s, pw])
    chk('rich: **đậm**', R('(**POLLUTE**)') == '(<b>POLLUTE</b>)')
    chk('rich: <u>gạch chân</u>', R('x <u>originated</u> y') == 'x <u>originated</u> y')
    chk('rich: *nghiêng*', R('an *old* man') == 'an <i>old</i> man')
    chk('rich: lồng nhau', R('**<u>two words</u>**') == '<b><u>two words</u></b>')
    chk('rich: bọc từng từ (hàng flex)', R('**<u>two words</u>**', True) == '<b><u>two</u></b> <b><u>words</u></b>')
    chk('rich: dấu lẻ / dấu * giữa số giữ nguyên', R('a * b * c') == 'a * b * c' and R('**a') == '**a' and R('<u>a') == '&lt;u&gt;a')
    chk('rich: không chạm vào chỗ trống ___', R('a ___ b ___ c') == 'a ___ b ___ c')
    chk('rich: HTML lạ vẫn bị escape', '<script' not in R('<script>x</script>') and '&lt;script' in R('<script>x</script>'))
    r = pg.evaluate("""(m)=>{const o=readMd(m);return o.tasks.map(x=>x.err?{err:x.err}:{no:x.no,ti:x.t.title,ins:x.t.instruction,kind:x.t.answer.kind,A:x.t.answer.layout,img:!!x.t.image,num:x.t.layout.num,lines:x.t.answer.params.lines,notes:x.notes,joined:x.joined,items:its(x.t).map(i=>({text:i.text,opts:i.opts||null}))})}""", MD)
    chk('4 Task + 1 phần tự tách = 5 khối, không lỗi', len(r) == 5 and all('err' not in x for x in r), [x.get('no') for x in r])
    if len(r) == 5 and all('err' not in x for x in r):
        t6, t7a, t7b, t8, t11 = r
        chk('Task 7 tách làm 2 phần: 7a 2 câu, 7b 2 câu', (t7a['no'], len(t7a['items']), t7b['no'], len(t7b['items'])) == ('7a', 2, '7b', 2) or (t7a['no'], t7b['no']) == ('2a', '2b'), [(x['no'], len(x['items'])) for x in r])
        chk('7b: dòng chỉ dẫn dưới thành hướng dẫn của phần 2', t7b['ins'].startswith('Mark the letter A, B, C or D indicate') and t7b['joined'])
        chk('7b: mọi câu có 4 lựa chọn, khoanh A/B/C (kế thừa)', all(i['opts'] and len(i['opts']) == 4 for i in t7a['items'] + t7b['items']) and t7b['kind'] == 'choice' and t7b['A'] == 'A4')
        chk('7b: có ghi chú báo việc tách', any('tách' in n for n in t7b['notes']), t7b['notes'])
        chk('7a: hướng dẫn gốc giữ nguyên, câu 1 giữ <u>', t7a['ins'].startswith('Mark the letter A, B, C or D on your') and '<u>originated</u>' in t7a['items'][0]['text'])
        chk('Task 8: giữ dòng ‘ ___ ’', '___' in t8['items'][0]['text'] and len(t8['items']) == 1)
        chk('Task 11: khung viết, không ảnh, không số, 15 dòng', t11['kind'] == 'sentence' and t11['A'] == 'A1' and not t11['img'] and t11['num'] == 'off' and t11['lines'] == 15, t11)
        chk('Task 11: có ghi chú', any('khung viết' in n for n in t11['notes']), t11['notes'])
    # nhập qua hộp + Task, kiểm hiển thị
    pg.evaluate("commit(w=>{w.tasks=[]})"); pg.wait_for_timeout(300)
    pg.click('#tree [data-lib]'); pg.click('#libDlg [data-tab=src]'); pg.wait_for_timeout(300)
    pg.fill('#libDlg textarea', MD); pg.wait_for_timeout(1200)
    chk('hộp nhập không báo lỗi', 'Cannot read' not in pg.inner_text('#libDlg'))
    pg.locator('#libDlg button', has_text='Thêm').last.click(); pg.wait_for_timeout(1200)
    chk('nhập được 5 Task', pg.evaluate("ws.tasks.length") == 5)
    chk('0 tràn', 'Không lỗi tràn' in pg.inner_text('#diagBadge'), pg.inner_text('#diagBadge'))
    chk('không cảnh báo nội dung (kể cả khung viết rỗng)', pg.evaluate("ws.tasks.every(t=>!contentWarnings(t).length)"), pg.evaluate("ws.tasks.map(t=>contentWarnings(t).map(x=>x.m))"))
    H = pg.evaluate("[...document.querySelectorAll('.page')].map(e=>e.innerHTML).join('')")
    chk('trang: POLLUTE in đậm', '<b>POLLUTE</b>' in H)
    chk('trang: originated gạch chân', '<u>originated</u>' in H)
    chk('trang: Task 6 câu 2 vừa nghiêng vừa đậm + gạch chân', '<i>old</i>' in H and '<b><u>park</u></b>' in H)
    chk('trang: ‘ ___ ’ là gạch thật (không phải chữ _)', '<span class="gap"></span>' in H and '______' not in H)
    gw = pg.evaluate("(()=>{const g=document.querySelector('.page .gap');if(!g)return 0;const r=g.getBoundingClientRect();return [r.width,r.height]})()")
    chk('gạch rộng ≥ 15 mm (≈57 px ở 100%)', gw and gw[0] > 40, gw)
    nl = pg.evaluate("[...document.querySelectorAll('.page .task')].pop().querySelectorAll('.a1 .ln').length")
    chk('Task 11: 15 dòng kẻ trên trang', nl == 15, nl)
    chk('Task 11: không có ô ảnh', pg.evaluate("[...document.querySelectorAll('.page .task')].pop().querySelectorAll('.pic').length") == 0)
    # khứ hồi MD
    md = pg.evaluate("sheetToMd(ws)")
    chk('xuất MD giữ ký hiệu', '**POLLUTE**' in md and '<u>originated</u>' in md and '<u>walked slowly</u>' in md)
    rt = pg.evaluate("(m)=>readMd(m).tasks.map(x=>x.err||[x.t.title,its(x.t).length,x.t.answer.layout,x.t.answer.params.lines||0])", md)
    chk('khứ hồi MD: số Task giữ nguyên, Task 11 vẫn là khung viết 15 dòng', len(rt) == 5 and rt[-1][2] == 'A1' and rt[-1][3] == 15 and rt[-1][1] == 1, rt)
    chk('khứ hồi: không sinh dòng "1. " rỗng cho khung viết', not re.search(r'^1\.\s*$', md, re.M))
    # sửa ở cột trái giữ ký hiệu
    pg.evaluate("openTask=ws.tasks[0].id; sel={type:'task',id:ws.tasks[0].id}; refreshSel()"); pg.wait_for_timeout(400)
    v = pg.evaluate("(()=>{const e=document.querySelector('#tree [data-k=\"it.0.text\"]');return e?e.value:null})()")
    chk('cột trái hiện nguyên ký hiệu **…**', v and '**POLLUTE**' in v, v)
    # xóa khung ảnh
    pg.evaluate("commit(w=>{w.tasks=[]})"); pg.wait_for_timeout(300)
    pg.evaluate("(m)=>{const o=readMd(m);commit(w=>{w.tasks.push(o.tasks[0].t)})}", "## Task: Colour\nHướng dẫn: Colour the picture.\nẢnh: tranh\nTrả lời: không\n"); pg.wait_for_timeout(600)
    chk('Task có khung ảnh trước khi xóa', pg.evaluate("!!ws.tasks[0].image") and pg.evaluate("document.querySelectorAll('.page .task .pic').length") >= 1)
    pg.evaluate("sel={type:'node',id:ws.tasks[0].id,g:'G1'}; openTask=ws.tasks[0].id; refreshSel()"); pg.wait_for_timeout(400)
    btn = pg.locator('[data-act="img-del"]')
    chk('có nút Xóa khung ảnh ở cột phải', btn.count() >= 1, btn.count())
    if btn.count():
        btn.first.click(); pg.wait_for_timeout(600)
        chk('đã xóa khung ảnh khỏi Task', pg.evaluate("!ws.tasks[0].image") and pg.evaluate("document.querySelectorAll('.page .task .pic').length") == 0)
        pg.click('#undo'); pg.wait_for_timeout(400)
        chk('Hoàn tác khôi phục khung ảnh', pg.evaluate("!!ws.tasks[0].image"))
    pg.screenshot(path='/tmp/test28.png')
    print('ERRS', errs); chk('0 lỗi console', not errs, errs)
    b.close()
print('ALL OK' if ok else 'SOME FAIL')
